#define O_WRONLY  0x001   // Write-only
#define O_RDWR    0x002   // Read and write
#define O_CREATE  0x100   // Create a new file if it doesn't exist
#define O_TRUNC   0x200   // Truncate the file to zero length
#define O_APPEND  0x400   // Append on each write
